#!/usr/bin/env bash
# lib/container_logs.sh - a size limit on every container's log.
#
# Docker's default json-file driver keeps a container's output forever, and
# nothing upstream's docker-compose.yml sets changes that, so the Supabase
# containers' logs grow until the disk is full. The limit goes on our own
# containers (frontend, MDM proxy) as `docker run --log-opt` arguments, and on
# the Supabase stack through a generated Compose overlay registered in
# COMPOSE_FILE - the same mechanism as the storage and auth overlays
# (docs/DECISIONS.md #28, #32). /etc/docker/daemon.json is left alone: it would
# change every container on the host (a Zoraxy container, say) and needs a
# Docker restart. See docs/DECISIONS.md #34.
#
# The overlay names every service the stack has, read from Compose itself, so
# it is regenerated whenever that can change: install (before and after the
# analytics overlay adds its services), `update supabase` and `repair apply`.
# shellcheck shell=bash

CONTAINER_LOGS_OVERLAY="docker-compose.sentinel-logging.yml"

# Non-secret config, persisted in installer.env.
CONTAINER_LOG_MAX_SIZE="50m"
CONTAINER_LOG_MAX_FILES="3"

_container_logs_overlay_path() { printf '%s/%s' "$SUPABASE_DIR" "$CONTAINER_LOGS_OVERLAY"; }

# The configured limits, as docker accepts them; a hand-edited value that is
# not one falls back to the default rather than reaching Compose.
container_log_max_size() {
    if [[ "$CONTAINER_LOG_MAX_SIZE" =~ ^[1-9][0-9]*[kmg]$ ]]; then
        printf '%s' "$CONTAINER_LOG_MAX_SIZE"
    else
        log_warn "CONTAINER_LOG_MAX_SIZE='${CONTAINER_LOG_MAX_SIZE}' is not a size like 50m; using 50m." >&2
        printf '50m'
    fi
}

container_log_max_files() {
    if [[ "$CONTAINER_LOG_MAX_FILES" =~ ^[1-9][0-9]?$ ]]; then
        printf '%s' "$CONTAINER_LOG_MAX_FILES"
    else
        log_warn "CONTAINER_LOG_MAX_FILES='${CONTAINER_LOG_MAX_FILES}' is not a file count; using 3." >&2
        printf '3'
    fi
}

# `docker run` arguments for a container the installer starts itself, one per
# line: mapfile -t args < <(container_log_run_args)
container_log_run_args() {
    printf '%s\n' --log-driver json-file \
        --log-opt "max-size=$(container_log_max_size)" \
        --log-opt "max-file=$(container_log_max_files)"
}

# Print the overlay for the service names on stdin, one per line.
container_logs_render_overlay() {
    local size files service
    size="$(container_log_max_size)"
    files="$(container_log_max_files)"
    printf '# Generated by sentinel-ops (lib/container_logs.sh). Do not edit: it is\n'
    printf '# rewritten on every install, `update supabase` and `repair apply` run.\n'
    printf '# Set CONTAINER_LOG_MAX_SIZE/CONTAINER_LOG_MAX_FILES in config/installer.env.\n'
    printf 'services:\n'
    while IFS= read -r service; do
        [[ -n "$service" ]] || continue
        printf '  %s:\n' "$service"
        printf '    logging:\n'
        printf '      driver: json-file\n'
        printf '      options:\n'
        printf "        max-size: '%s'\n" "$size"
        printf "        max-file: '%s'\n" "$files"
    done
}

# Every service of the stack, from Compose, with this overlay left out of the
# file list: an overlay that still names a service upstream has since removed
# would otherwise make Compose refuse the very config it is regenerated from.
_container_logs_services() {
    local current entry listed=() files=()
    current="$(env_get "${SUPABASE_DIR}/.env" COMPOSE_FILE 2>/dev/null || true)"
    [[ -n "$current" ]] || current="docker-compose.yml"
    IFS=':' read -r -a listed <<<"$current"
    for entry in "${listed[@]}"; do
        [[ -z "$entry" || "$entry" == "$CONTAINER_LOGS_OVERLAY" ]] && continue
        files+=(-f "$entry")
    done
    (cd "$SUPABASE_DIR" && "${DOCKER_COMPOSE_CMD[@]}" --env-file "${SUPABASE_DIR}/.env" \
        "${files[@]}" config --services 2>>"${SO_LOG_FILE:-/dev/null}") | LC_ALL=C sort -u
}

# Everything container_logs_apply_config can change, as one string - lets a
# caller tell whether a re-apply changed anything (and so needs a restart).
_container_logs_fingerprint() {
    printf '%s|%s' \
        "$(env_get "${SUPABASE_DIR}/.env" COMPOSE_FILE 2>/dev/null || true)" \
        "$(cat "$(_container_logs_overlay_path)" 2>/dev/null || true)"
}

# Write the overlay and register it. Safe to call on every install, update
# and repair: the file is only rewritten when its content changes. When the
# services cannot be read, whatever overlay is there is left as it is.
container_logs_apply_config() {
    local env_file="${SUPABASE_DIR}/.env" overlay services tmp
    [[ -f "$env_file" ]] || { log_error "Missing ${env_file}"; return 1; }
    overlay="$(_container_logs_overlay_path)"

    services="$(_container_logs_services)" || services=""
    if [[ -z "$services" ]]; then
        log_warn "Could not list the Supabase services; container log limits not updated."
        return 1
    fi

    tmp="$(mktemp)"
    container_logs_render_overlay <<<"$services" >"$tmp"
    if ! cmp -s "$tmp" "$overlay" 2>/dev/null; then
        cat "$tmp" >"$overlay"
    fi
    rm -f "$tmp"
    compose_file_register "$env_file" "$CONTAINER_LOGS_OVERLAY" present
    log_ok "Container logs capped at $(container_log_max_files) x $(container_log_max_size) per service"
    return 0
}

# True when the overlay is on disk and listed in COMPOSE_FILE.
container_logs_overlay_registered() {
    local current
    [[ -f "$(_container_logs_overlay_path)" ]] || return 1
    current="$(env_get "${SUPABASE_DIR}/.env" COMPOSE_FILE 2>/dev/null || true)"
    [[ ":${current}:" == *":${CONTAINER_LOGS_OVERLAY}:"* ]]
}
